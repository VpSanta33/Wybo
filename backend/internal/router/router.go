package router

import (
	"github.com/gin-gonic/gin"
	"github.com/wybo/backend/internal/config"
	"github.com/wybo/backend/internal/handler"
	"github.com/wybo/backend/internal/middleware"
	"github.com/wybo/backend/internal/service"
	"go.uber.org/zap"
	"gorm.io/gorm"
	"time"
)

// New 构造 Gin 引擎并注册路由
func New(db *gorm.DB, cfg *config.Config, logger *zap.Logger) *gin.Engine {
	svc := service.New(db, cfg, logger)
	h := handler.New(svc, cfg, logger)

	r := gin.New()
	r.Use(gin.Recovery())
	r.Use(middleware.CORS())
	if err := r.SetTrustedProxies(cfg.Server.TrustedProxies); err != nil {
		panic("invalid trusted proxy configuration")
	}
	r.GET("/healthz", handler.Health)
	r.Static("/uploads", cfg.Upload.Dir)

	api := r.Group("/api/v1")
	api.Use(h.StorefrontScope)
	{
		// 公开接口
		api.GET("/site", h.Site)
		api.GET("/categories", h.Categories)
		api.GET("/products", h.Products)
		api.GET("/products/:id", h.ProductDetail)
		api.GET("/announcements", h.Announcements)
		api.GET("/gateways", h.PublicGateways)
		api.POST("/visits", middleware.RateLimit(120, time.Minute), h.RecordVisit)
		api.POST("/agent/login", middleware.RateLimit(10, time.Minute), h.AgentLogin)
		api.GET("/agent/portal", h.AgentPortal)
		api.GET("/orders/:orderNo/tickets", middleware.RateLimit(30, time.Minute), h.CustomerTickets)
		api.POST("/orders/:orderNo/tickets", middleware.RateLimit(10, time.Minute), h.CustomerCreateTicket)
		api.POST("/orders/:orderNo/tickets/:number/replies", middleware.RateLimit(20, time.Minute), h.CustomerReplyTicket)
		api.POST("/orders", middleware.RateLimit(10, time.Minute), h.CreateOrder)
		api.GET("/orders/:orderNo", middleware.RateLimit(30, time.Minute), h.GetOrder)
		api.POST("/orders/:orderNo/cancel", h.CancelOrder)
		api.POST("/orders/:orderNo/pay", middleware.RateLimit(12, time.Minute), h.Pay)
		api.GET("/query", middleware.RateLimit(30, time.Minute), h.Query)
		api.POST("/pay/notify/:gateway", h.PayNotify)
		api.GET("/pay/notify/:gateway", h.PayNotify)
		api.GET("/pay/return", h.PayReturn)

		api.POST("/events", middleware.RateLimit(60, time.Minute), h.RecordFunnel)

		api.POST("/station/apply", middleware.RateLimit(3, time.Hour), h.StationApply)
		api.POST("/station/activate", middleware.RateLimit(8, time.Minute), h.StationActivate)
		api.POST("/station/login", middleware.RateLimit(10, time.Minute), h.StationLogin)
		station := api.Group("/station/admin")
		station.Use(h.StationAuth)
		{
			station.GET("/dashboard", h.StationDashboard)
			station.GET("/products", h.StationProducts)
			station.PUT("/products/:id", h.StationProduct)
			station.PUT("/settings", h.StationBrand)
			station.GET("/orders", h.StationOrders)
			station.GET("/tickets", h.StationTickets)
			station.GET("/tickets/:number", h.StationTickets)
			station.POST("/tickets/:number/replies", h.StationReply)
			station.POST("/settlements", middleware.RateLimit(5, time.Minute), h.StationSettlement)
			station.POST("/upload", middleware.RateLimit(20, time.Hour), h.AdminSiteImage)
			station.PUT("/security", middleware.RateLimit(10, time.Minute), h.StationSecurity)
			station.POST("/security/totp/setup", middleware.RateLimit(5, time.Minute), h.StationTOTPSetup)
			station.POST("/security/totp/enable", middleware.RateLimit(5, time.Minute), h.StationTOTPEnable)
		}
		// 管理端
		admin := api.Group("/admin")
		admin.POST("/entry", middleware.RateLimit(30, time.Minute), h.AdminEntry)
		admin.Use(h.AdminPathGuard)
		admin.POST("/login", middleware.RateLimit(10, time.Minute), h.AdminLogin)
		admin.Use(middleware.JWTAuth(cfg.JWT.Secret, svc.ValidateSession))
		admin.Use(h.AdminAudit)
		admin.Use(h.AdminPermissions)
		admin.Use(h.AdminStepUp)
		{
			admin.POST("/confirm", middleware.RateLimit(10, time.Minute), h.AdminConfirm)
			admin.GET("/stations", h.AdminStations)
			admin.POST("/stations", h.AdminStationCreate)
			admin.PUT("/stations/:id", h.AdminStationUpdate)
			admin.PUT("/stations/:id/status", h.AdminStationStatus)
			admin.GET("/stations/:id/products", h.AdminStationProducts)
			admin.PUT("/stations/:id/products", h.AdminStationProduct)
			admin.POST("/stations/:id/invite", h.AdminStationInvite)
			admin.POST("/stations/:id/reset-2fa", h.AdminStationResetTOTP)
			admin.POST("/station-applications/:id/reject", h.AdminStationReject)
			admin.GET("/readiness", h.AdminReadiness)
			admin.POST("/readiness/https", middleware.RateLimit(6, time.Minute), h.AdminTestHTTPS)
			admin.POST("/readiness/email", middleware.RateLimit(3, time.Minute), h.AdminTestEmail)
			admin.GET("/monitor", h.AdminMonitor)
			admin.PUT("/monitor", h.AdminMonitorSettings)
			admin.POST("/monitor/cleanup", h.AdminCleanup)
			admin.GET("/analytics/funnel", h.AdminFunnel)
			admin.GET("/purchases", h.AdminProcurement)
			admin.POST("/suppliers", h.AdminSaveSupplier)
			admin.PUT("/suppliers/:id", h.AdminSaveSupplier)
			admin.POST("/purchases", h.AdminCreatePurchase)
			admin.POST("/purchases/:id/payment", h.AdminPurchasePayment)
			admin.POST("/purchases/:id/receive", h.AdminReceivePurchase)
			admin.POST("/purchases/:id/cancel", h.AdminCancelPurchase)
			admin.GET("/after-sales", h.AdminAfterSales)
			admin.POST("/after-sales/replace", h.AdminReplaceCard)
			admin.POST("/after-sales/upgrade", h.AdminUpgrade)
			admin.POST("/after-sales/refund", h.AdminDeliveredRefund)
			admin.POST("/settlements/:id/cancel", h.AdminCancelSettlement)
			admin.GET("/staff", h.AdminStaff)
			admin.POST("/staff", h.AdminSaveStaff)
			admin.PUT("/staff/:id", h.AdminSaveStaff)
			admin.POST("/cards/:id/reveal", h.AdminRevealCard)
			admin.GET("/reports", h.AdminReports)
			admin.PUT("/orders/:orderNo/fee", h.AdminFee)
			admin.GET("/payment-operations", h.AdminPaymentOps)
			admin.POST("/reconcile/:id", h.AdminReconcile)
			admin.POST("/payment-issues/:id/resolve", h.AdminResolveIssue)
			admin.GET("/batches", h.AdminBatches)
			admin.GET("/stock-alerts", h.AdminAlerts)
			admin.POST("/auto-deliver", h.AdminAutoDeliver)
			admin.PUT("/agents/:id/password", h.AdminAgentPassword)
			admin.POST("/agents/:id/settlements", h.AdminCreateSettlement)
			admin.GET("/settlements", h.AdminSettlements)
			admin.POST("/settlements/:id/paid", h.AdminPaySettlement)
			admin.POST("/coupons/batch", h.AdminBatchCoupons)
			admin.GET("/audit-logs", h.AdminAuditLogs)
			admin.GET("/backups", h.AdminBackups)
			admin.POST("/backups", h.AdminCreateBackup)
			admin.GET("/backups/:id/download", h.AdminDownloadBackup)
			admin.POST("/backups/:id/prepare-restore", h.AdminPrepareRestore)
			admin.GET("/tickets", h.AdminTickets)
			admin.GET("/tickets/:number", h.AdminTickets)
			admin.POST("/tickets/:number/replies", h.AdminReplyTicket)
			admin.GET("/me", h.AdminMe)
			admin.PUT("/security", h.AdminSecurity)
			admin.POST("/security/totp/setup", h.AdminTOTPSetup)
			admin.POST("/security/totp/enable", h.AdminTOTPEnable)
			admin.GET("/agents", h.AdminAgents)
			admin.POST("/agents", h.AdminSaveAgent)
			admin.PUT("/agents/:id", h.AdminSaveAgent)
			admin.GET("/dashboard", h.AdminDashboard)
			admin.GET("/orders", h.AdminOrders)
			admin.GET("/orders/:orderNo", h.AdminOrderDetail)
			admin.GET("/notifications", h.AdminNotifications)
			admin.POST("/notifications/:id/retry", h.AdminRetryNotification)
			admin.POST("/orders/:orderNo/refund", h.AdminRefund)
			admin.POST("/orders/:orderNo/deliver", h.AdminManualDeliver)
			admin.POST("/orders/:orderNo/fulfill", h.AdminManualFulfill)
			admin.GET("/cards", h.AdminCards)
			admin.POST("/cards/import", h.AdminImportCards)
			admin.POST("/cards/:id/disable", h.AdminDisableCard)
			admin.DELETE("/cards/:id", h.AdminDeleteCard)
			admin.GET("/categories", h.AdminListCategories)
			admin.POST("/categories", h.AdminCreateCategory)
			admin.PUT("/categories/:id", h.AdminUpdateCategory)
			admin.DELETE("/categories/:id", h.AdminDeleteCategory)
			admin.GET("/products", h.AdminListProducts)
			admin.POST("/products", h.AdminCreateProduct)
			admin.PUT("/products/:id", h.AdminUpdateProduct)
			admin.DELETE("/products/:id", h.AdminDeleteProduct)
			admin.GET("/gateways", h.AdminListGateways)
			admin.PUT("/gateways/:code", h.AdminUpdateGateway)
			admin.POST("/gateways/:code/logo", h.AdminPaymentLogo)
			admin.GET("/coupons", h.AdminListCoupons)
			admin.POST("/coupons", h.AdminCreateCoupon)
			admin.PUT("/coupons/:id", h.AdminUpdateCoupon)
			admin.DELETE("/coupons/:id", h.AdminDeleteCoupon)
			admin.GET("/announcements", h.AdminListAnnouncements)
			admin.POST("/announcements", h.AdminCreateAnnouncement)
			admin.PUT("/announcements/:id", h.AdminUpdateAnnouncement)
			admin.DELETE("/announcements/:id", h.AdminDeleteAnnouncement)
			admin.GET("/settings", h.AdminGetSettings)
			admin.PUT("/settings", h.AdminUpdateSettings)
			admin.POST("/settings/image", h.AdminSiteImage)
			admin.POST("/upload", h.AdminUpload)
		}
	}
	return r
}
